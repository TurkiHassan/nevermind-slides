export type Lang = 'ar' | 'en';

const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';

/** Western digits to Arabic-Indic in Arabic mode (counts, slide numbers, zoom); values tied to code stay Western. */
export function digits(value: string | number, lang: Lang): string {
  const s = String(value);
  return lang === 'ar' ? s.replace(/[0-9]/g, (d) => AR_DIGITS[Number(d)]) : s;
}

const pad2 = (n: number) => String(n).padStart(2, '0');

function arLines(n: number): string {
  if (n === 1) return 'سطر';
  if (n === 2) return 'سطران';
  if (n % 100 >= 3 && n % 100 <= 10) return 'أسطر';
  return 'سطرًا';
}

