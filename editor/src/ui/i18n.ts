/** Arabic names for the colour tokens the nevermind skill uses; other tokens show their own name. */
const COLOUR_NAMES_AR: Record<string, string> = {
  bone: 'عظمي', cream: 'كريمي', ink: 'حبري', muted: 'رمادي خافت', navy: 'كحلي', blue: 'أزرق', verm: 'قرمزي',
  line: 'لون الخطوط', accent: 'لون التمييز', page: 'لون الصفحة', outer: 'الخلفية', white: 'أبيض', black: 'أسود',
  red: 'أحمر', green: 'أخضر', mint: 'نعناعي', lavender: 'خزامي', pink: 'وردي', sky: 'سماوي', paper: 'ورقي',
};

export function colourName(token: string, lang: Lang): string {
  if (lang === 'en') return token;
  const parts = token.split('-');
  const last = COLOUR_NAMES_AR[parts[parts.length - 1]];
  return COLOUR_NAMES_AR[token] ?? last ?? token;
}

